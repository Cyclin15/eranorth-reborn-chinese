DISPLAY = ("Title", "Narrative")

def is_display(k):
    if k in DISPLAY:
        return True
    if k.startswith("Choice_"):
        rest = k[len("Choice_"):]
        if rest.isdigit():
            return True
        if rest.endswith("_Outcome") and rest[:-len("_Outcome")].isdigit():
            return True
    return False

os.makedirs(OUT, exist_ok=True)
names = [l.strip() for l in open(LIST, encoding="utf-8") if l.strip()]
assert len(names) == len(T), (len(names), len(T))

for name in names:
    path = os.path.join(SRC, name)
    raw = open(path, encoding="utf-8", newline="").read()
    data = json.loads(raw)
    trans = T[name]
    # every non-empty display field must be translated
    for k, v in data.items():
        if is_display(k) and isinstance(v, str) and v and k not in trans:
            raise SystemExit("missing translation: %s %s" % (name, k))
    for k in trans:
        if not is_display(k):
            raise SystemExit("translation for non-display field: %s %s" % (name, k))
    for key, tv in trans.items():
        ov = data[key]
        old = '"%s": %s' % (key, json.dumps(ov, ensure_ascii=False))
        new = '"%s": %s' % (key, json.dumps(tv, ensure_ascii=False))
        cnt = raw.count(old)
        assert cnt == 1, (name, key, cnt)
        raw = raw.replace(old, new)
    with open(os.path.join(OUT, name), "w", encoding="utf-8", newline="") as f:
        f.write(raw)
    print("OK", name)

print("ALL DONE:", len(names), "files")

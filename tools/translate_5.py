def main():
    os.makedirs(DST, exist_ok=True)
    names = [l.strip() for l in open(r"C:\Users\Administrator\AppData\Local\Temp\eran_l10n\tales_group_5.txt", encoding="utf-8") if l.strip()]
    assert set(names) == set(T.keys()), (set(names) ^ set(T.keys()))
    for fname in names:
        raw = open(os.path.join(SRC, fname), encoding="utf-8").read()
        for key, val in T[fname].items():
            pat = re.compile('("' + key + r'"\s*:\s*)"(?:[^"\\]|\\.)*"')
            n = len(pat.findall(raw))
            assert n == 1, "key %s found %d times in %s" % (key, n, fname)
            raw = pat.sub(lambda m: m.group(1) + json.dumps(val, ensure_ascii=False), raw, count=1)
        with open(os.path.join(DST, fname), "wb") as f:
            f.write(raw.encode("utf-8"))
        print("OK", fname)

if __name__ == "__main__":
    main()
